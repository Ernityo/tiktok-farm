"""Turn trainer recordings into thumb-side swipe profiles for the bot.

Reads every trainer-*.json in trainer-app/recordings/, keeps the swipe-up gestures,
groups them by which finger swipes, and writes src/devices/swipe-profile-data.ts.
Only shape numbers are kept (no coordinates), one row per swipe.
"""
import glob, json, math, os, statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(os.path.dirname(ROOT), 'src', 'devices', 'swipe-profile-data.ts')

def profile_for(hands: str) -> str | None:
    h = hands.lower()
    if 'left index' in h: return 'left-index'
    if 'right index' in h: return 'right-index'
    if 'right thumb' in h: return 'right-thumb'
    if 'left thumb' in h: return 'left-thumb'
    return None

def shape(samples, dur):
    a, b = samples[0], samples[-1]
    dx, dy = b['x'] - a['x'], b['y'] - a['y']
    L = math.hypot(dx, dy) or 1
    # signed x-offset of the point furthest from the straight path, as a fraction of its length
    best = 0.0
    for p in samples:
        t = (p['y'] - a['y']) / ((b['y'] - a['y']) or 1)
        off = p['x'] - (a['x'] + t * dx)
        if abs(off) > abs(best): best = off
    touch = next((p['tMs'] for p in samples if math.hypot(p['x'] - a['x'], p['y'] - a['y']) > 2), 0)
    return {
        'travel': round(a['y'] - b['y'], 1),
        'duration': round(dur, 1),
        'touchDown': round(touch, 1),
        'bow': round(best / L, 4),
        'drift': round(dx, 1),
        'startX': round(a['x'], 1), 'startY': round(a['y'], 1),
        'endX': round(b['x'], 1), 'endY': round(b['y'], 1),
    }

rows = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'recordings', 'trainer-*.json'))):
    data = json.load(open(path))
    hands = {s['id']: s['hands'] for s in data['steps']}
    for g in data['gestures']:
        if g['kind'] != 'swipe_up' or len(g['samples']) < 3: continue
        name = profile_for(hands[g['stepId']])
        if name is None: continue
        rows.setdefault(name, []).append(shape(g['samples'], g['durationMs']))

order = ['right-thumb', 'left-thumb', 'left-index', 'right-index']
FIELDS = ['startX', 'startY', 'endX', 'endY', 'travel', 'duration', 'touchDown']
rules_lines = ['export interface SwipeRules {',
               '    ranges: Record<"startX" | "startY" | "endX" | "endY" | "travel" | "duration" | "touchDown", readonly [number, number]>;',
               '    bowMagnitude: readonly [number, number];',
               '    bowSign: 1 | -1;',
               '}',
               'export const SWIPE_PROFILE_RULES: Record<string, SwipeRules> = {']
for name in order:
    xs = rows.get(name, [])
    if not xs: continue
    ranges = ', '.join(f"{f}: [{min(r[f] for r in xs)}, {max(r[f] for r in xs)}]" for f in FIELDS)
    mags = [abs(r['bow']) for r in xs]
    sign = 1 if st.median(r['bow'] for r in xs) > 0 else -1
    rules_lines.append(f"    '{name}': {{ ranges: {{ {ranges} }}, bowMagnitude: [{min(mags)}, {max(mags)}], bowSign: {sign} }},")
rules_lines.append('};')
lines = ['// Generated by trainer-app/tools/build_swipe_profiles.py. Do not edit by hand.',
         'export interface SwipeRow { travel: number; duration: number; touchDown: number; bow: number; drift: number; startX: number; startY: number; endX: number; endY: number }',
         'export const SWIPE_PROFILE_DATA: Record<string, readonly SwipeRow[]> = {']
for name in order:
    xs = rows.get(name, [])
    lines.append(f"    '{name}': [")
    for r in xs:
        lines.append(f"        {{ travel: {r['travel']}, duration: {r['duration']}, touchDown: {r['touchDown']}, bow: {r['bow']}, drift: {r['drift']}, startX: {r['startX']}, startY: {r['startY']}, endX: {r['endX']}, endY: {r['endY']} }},")
    lines.append('    ],')
lines.append('};')
lines += rules_lines
open(OUT, 'w').write('\n'.join(lines) + '\n')
for name in order:
    xs = rows.get(name, [])
    if not xs: print(name, 'no data'); continue
    print(f"{name:12} n={len(xs):3}  travel {st.median(r['travel'] for r in xs):.0f}  dur {st.median(r['duration'] for r in xs):.0f}  "
          f"bow {st.median(r['bow'] for r in xs):+.3f}  bow<0 share {sum(r['bow'] < 0 for r in xs)/len(xs):.0%}  drift {st.median(r['drift'] for r in xs):+.0f}")
print('wrote', OUT)
